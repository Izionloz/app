"""Writes eva/app/hud/layouts/eva_v12_gpu.json: EVA V12 with its three biggest numbers (the speed, the rpm, the gear) as `atext` widgets: the GPU of the
cluster draws them from a glyph atlas that goes up once (an R8 asset), and a new value is one small uniform message, no pixels (shared/hud.js `atext`,
after robertnisipeanu/idrive-apps' showcase). Each is a layer of its own, put on a second connection to cluster-render (conn 1: 8 layers per connection)
so that the 8 layers of the rest stay. No glow on these three (a GPU text has none); the rest is V12 as it is. Run gen_layout_v12.py first."""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
LAY = os.path.join(HERE, '..', 'app', 'hud', 'layouts')
FONTS = os.path.join(HERE, '..', 'app', 'hud', 'fonts')


def cell_w(font):
    """The atlas cell's width as hud.js _atlas makes it: the widest advance of the first 64 printable glyphs, plus 2."""
    g = json.load(open(os.path.join(FONTS, font + '.json')))['glyphs']
    chars = sorted(c for c in g if len(c) == 1 and ' ' <= c <= '~')[:64]
    return int(-(-max(g[c]['advance'] for c in chars) // 1)) + 2


base = json.load(open(os.path.join(LAY, 'eva_v12.json')))
out = []
for w in base['widgets']:
    if w['id'] in ('speed', 'rpm', 'gear'):
        cells = {'speed': 3, 'rpm': 4, 'gear': 1}[w['id']]
        cw = cell_w(w['font'])
        # the cells are all alike, so the number is right-aligned in them (the speed and the rpm: the last digit stays where it is); the gear is one cell,
        # centred where the text widget was, and shows the selector letter or the gear number ({{gearnum}}; the programme is in the row below)
        right = w['x'] + w['w'] - (24 if w['id'] == 'rpm' else 0)
        x = w['x'] + (w['w'] - cw) // 2 if w['id'] == 'gear' else right - cells * cw
        a = {'id': w['id'], 'type': 'atext', 'class': w['class'], 'z': w['z'], 'x': x, 'y': w['y'], 'w': cells * cw, 'h': w['h'], 'cells': cells,
             'text': '{{gearnum}}' if w['id'] == 'gear' else w['text'], 'font': w['font'], 'color': w['color'], 'align': 'right', 'rate': 1, 'conn': 1}
        out.append(a)
    else:
        out.append(w)
with open(os.path.join(LAY, 'eva_v12_gpu.json'), 'w') as f:
    json.dump({'schemaVersion': 2, 'name': 'EVA V12 GPU text', 'theme': 'eva', '_about': 'EVA V12 with the speed, the rpm and the gear drawn by the GPU (atext). Generated by eva/tools/gen_layout_v12_gpu.py.', 'widgets': out}, f, indent=1)
print('eva_v12_gpu.json', len(out), 'widgets')
